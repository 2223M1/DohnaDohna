import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { readBoard, diffBoard } from './card-board.mjs';
const { chromium } = createRequire(import.meta.url)(process.argv[2]);
const root = path.resolve('.');
const output = path.join(root, 'build/authoring-proof');
fs.mkdirSync(output, { recursive: true });
const baseline = JSON.parse(fs.readFileSync('Docs/authoring/card-board-baseline.json','utf8'));
const browser = await chromium.launch({headless:true,channel:'chrome'});
try {
  const page = await browser.newPage({viewport:{width:1540,height:980},acceptDownloads:true});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{ window.showSaveFilePicker=undefined; });
  await page.goto(pathToFileURL(path.join(root,'Docs/authoring/DohnaDohna-card-board.html')).href);
  assert.equal(await page.locator('.entry').count(),baseline.entries.length);
  await page.getByRole('button',{name:'安缇娜',exact:true}).click();
  await page.locator('#kind').selectOption('card');
  assert.equal(await page.locator('.entry').count(),15);
  const id='CARD.DOHNA_DOHNA_CARD_SQUAD_BALL_LIGHTNING';
  const card=page.locator(`[data-id="${id}"]`);
  await card.locator('[data-field=name]').fill('球状闪电 · 编辑验证');
  await card.locator('[data-field=cost]').fill('2');
  await card.locator('[data-field=text]').fill('测试基础文案 <script>不是脚本</script>');
  await card.locator('[data-field=upgradedText]').fill('测试升级文案');
  await card.locator('[data-field=melee]').check();
  await card.locator('[data-field=notes]').fill('独立 HTML 保存与字段差异测试');
  await card.locator('[data-field=mark]').selectOption('edit');
  await card.getByRole('button',{name:'下移',exact:true}).click();
  await page.screenshot({path:path.join(output,'board-edited.png')});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#save').click();
  const download=await downloadPromise;
  const returned=path.join(output,'returned.html');
  await download.saveAs(returned);
  const parsed=readBoard(fs.readFileSync(returned,'utf8'));
  const diff=diffBoard(baseline,parsed);
  const changes=diff.changed.find(e=>e.id===id).changes;
  for(const field of ['name','cost','text','upgradedText','melee','notes','mark','order']) assert(field in changes, field);
  await page.goto(pathToFileURL(returned).href);
  assert.equal(await page.locator(`[data-id="${id}"] [data-field=name]`).inputValue(),'球状闪电 · 编辑验证');
  await page.locator('#search').fill('球状闪电 · 编辑验证');
  assert.equal(await page.locator('.entry').count(),1);
  await page.locator('#add').click();
  const draft=page.locator('[data-id^="DRAFT."]');
  assert.equal(await draft.count(),1);
  page.once('dialog',dialog=>dialog.accept());
  await page.locator(`[data-id="${id}"]`).getByRole('button',{name:'删除条目',exact:true}).click();
  const html=await page.evaluate(()=>buildEditedHtml());
  const changed=diffBoard(baseline,readBoard(html));
  assert.equal(changed.added.length,1);assert.equal(changed.removed[0].id,id);
  assert.throws(()=>diffBoard(baseline,{...parsed,baselineHash:'wrong'}));
  assert.throws(()=>readBoard(html.replace('</body>','<script id="dohna-board-data" type="application/json">{}</script></body>')));
  // Executable text is not interpreted by the return path, even if a user adds it.
  assert.deepEqual(readBoard(html+'<script>throw new Error("MUST NOT EXECUTE")</script>'),readBoard(html));
  const altered=structuredClone(parsed);altered.entries[0].source='forged';
  assert.throws(()=>diffBoard(baseline,altered));
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(output,'diff.json'),JSON.stringify(diff,null,2));
  console.log('PASS browser input, edit, mark, reorder, save, reopen, add/delete, safe diff and baseline rejection');
} finally { await browser.close(); }
